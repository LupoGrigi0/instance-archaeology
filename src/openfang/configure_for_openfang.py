def load_json(path):
    """Load a JSON file, return None if missing or invalid."""
    try:
        with open(path) as f:
            return json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        return None


def load_text(path):
    """Load a text file, return None if missing."""
    try:
        with open(path) as f:
            return f.read().strip()
    except FileNotFoundError:
        return None


def load_preferences(instance_id):
    """Load HACS instance preferences."""
    return load_json(INSTANCES_DIR / instance_id / "preferences.json")


def load_personality(personality_name):
    """Load personality.json and wisdom files for a personality."""
    if not personality_name:
        return None, []

    pdir = PERSONALITIES_DIR / personality_name
    pjson = load_json(pdir / "personality.json")
    if not pjson:
        return None, []

    wisdom_files = pjson.get("wisdomFiles", [])
    wisdom_contents = []
    for wf in wisdom_files:
        content = load_text(pdir / wf)
        if content:
            wisdom_contents.append(content)

    return pjson, wisdom_contents


def load_role(role_name):
    """Load role.json and wisdom files for a role."""
    if not role_name:
        return None, []

    rdir = ROLES_DIR / role_name
    rjson = load_json(rdir / "role.json")
    if not rjson:
        return None, []

    # Handle schema inconsistency: some roles have wisdomFiles, some don't
    wisdom_files = rjson.get("wisdomFiles", [])
    wisdom_contents = []

    # Check wisdom/ subdirectory if wisdomFiles specified
    for wf in wisdom_files:
        content = load_text(rdir / "wisdom" / wf)
        if not content:
            content = load_text(rdir / wf)
        if content:
            wisdom_contents.append(content)

    return rjson, wisdom_contents


def load_gestalt(instance_id):
    """Load gestalt.md if it exists (archaeology output)."""
    return load_text(INSTANCES_DIR / instance_id / "gestalt.md")


def load_project(project_name):
    """Load project preferences."""
    if not project_name:
        return None
    return load_json(PROJECTS_DIR / project_name / "preferences.json")


def get_active_instances():
    """List active (non-test) instances for team context.

    Filters out test/infra instances, deduplicates by name (keeps most recent),
    and excludes instances that haven't been active recently.
    """
    SKIP_PATTERNS = [
        "test", "sanity", "regression", "harness", "tester", "verifier",
        "containerize", "agenticframework", "msgtest", "openclaw",
    ]

    # Collect all real instances, track by name for dedup
    by_name = {}
    for d in sorted(INSTANCES_DIR.iterdir()):
        if not d.is_dir():
            continue
        prefs = load_json(d / "preferences.json")
        if not prefs:
            continue

        # Skip test/infra instances
        dir_lower = d.name.lower()
        if any(pat in dir_lower for pat in SKIP_PATTERNS):
            continue

        name = prefs.get("name", d.name)
        role = prefs.get("role", "")
        last_active = prefs.get("lastActiveAt", "")

        # Dedup by name: keep the one with most recent lastActiveAt
        if name in by_name:
            if last_active > by_name[name].get("lastActiveAt", ""):
                by_name[name] = {"id": d.name, "name": name, "role": role, "lastActiveAt": last_active}
        else:
            by_name[name] = {"id": d.name, "name": name, "role": role, "lastActiveAt": last_active}

    # Return sorted by name, without the lastActiveAt field
    return [{"id": v["id"], "name": v["name"], "role": v["role"]}
            for v in sorted(by_name.values(), key=lambda x: x["name"])]


