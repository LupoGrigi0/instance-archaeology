def find_used_ports():
    """Scan existing OpenFang configs for used ports."""
    used = set()
    for d in INSTANCES_DIR.iterdir():
        config = d / "openfang" / "config.toml"
        if config.exists():
            content = config.read_text()
            match = re.search(r'api_listen\s*=\s*"[^"]*:(\d+)"', content)
            if match:
                used.add(int(match.group(1)))
    return used


def allocate_port(used_ports):
    """Find next available port in the OpenFang range."""
    for port in range(PORT_RANGE_START, PORT_RANGE_END):
        if port not in used_ports:
            return port
    raise RuntimeError(f"No available ports in range {PORT_RANGE_START}-{PORT_RANGE_END}")


