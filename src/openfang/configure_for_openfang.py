def generate_config_toml(instance_id, prefs, port):
    """Generate config.toml content."""
    return CONFIG_TOML_TEMPLATE.format(
        instance_id=instance_id,
        name=prefs.get("name", ""),
        role=prefs.get("role", ""),
        project=prefs.get("project", ""),
        port=port,
        mcp_proxy_path=str(MCP_PROXY_PATH),
    )


def generate_agent_toml(instance_id, prefs, system_prompt):
    """Generate agent.toml content."""
    name = prefs.get("name", instance_id.split("-")[0])
    agent_name = name.lower()
    role = prefs.get("role", "")

    # Build description
    personality_json = None
    if prefs.get("personality"):
        personality_json, _ = load_personality(prefs["personality"])

    desc_parts = [name]
    if personality_json and personality_json.get("description"):
        desc_parts.append(f"— {personality_json['description']}")
    elif role:
        desc_parts.append(f"— {role}")

    description = " ".join(desc_parts)

    # Build tags
    tags = ["hacs"]
    if role:
        tags.append(role.lower())

    # Escape triple quotes in system_prompt (shouldn't happen, but safety)
    safe_prompt = system_prompt.replace('"""', '\\"\\"\\"')

    # Format tags as TOML array
    tags_str = "[" + ", ".join(f'"{t}"' for t in tags) + "]"

    return AGENT_TOML_TEMPLATE.format(
        instance_id=instance_id,
        agent_name=agent_name,
        description=description,
        tags=tags_str,
        system_prompt=safe_prompt,
    )


