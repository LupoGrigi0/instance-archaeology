def configure_instance(instance_id, port=None, dry_run=False, identity_only=False,
                       seed=True):
    """Generate OpenFang configuration for a HACS instance."""

    # Load HACS data
    prefs = load_preferences(instance_id)
    if not prefs:
        print(f"ERROR: No preferences.json found for {instance_id}", file=sys.stderr)
        return False

    name = prefs.get("name", instance_id.split("-")[0])
    agent_name = name.lower()

    gestalt = load_gestalt(instance_id)

    # Try explicit personality first, then fall back to name-matched personality dir
    personality_name = prefs.get("personality")
    if not personality_name:
        # Many instances have personality dirs named after them even when prefs.personality is null
        candidate = prefs.get("name", instance_id.split("-")[0])
        if (PERSONALITIES_DIR / candidate).is_dir():
            personality_name = candidate
    personality_json, personality_wisdom = load_personality(personality_name)

    role_json, role_wisdom = load_role(prefs.get("role"))
    project_prefs = load_project(prefs.get("project"))
    team = get_active_instances()

    # Compile system prompt
    system_prompt = compile_system_prompt(
        instance_id, prefs, gestalt, personality_json, personality_wisdom,
        role_json, role_wisdom, project_prefs, team
    )

    # Port allocation
    if not identity_only:
        if port is None:
            used_ports = find_used_ports()
            # If this instance already has a port, reuse it
            existing_config = INSTANCES_DIR / instance_id / "openfang" / "config.toml"
            if existing_config.exists():
                content = existing_config.read_text()
                match = re.search(r'api_listen\s*=\s*"[^"]*:(\d+)"', content)
                if match:
                    port = int(match.group(1))
            if port is None:
                port = allocate_port(used_ports)

    # Generate content
    if not identity_only:
        config_content = generate_config_toml(instance_id, prefs, port)
    agent_content = generate_agent_toml(instance_id, prefs, system_prompt)

    # Output
    if dry_run:
        if not identity_only:
            print("=" * 60)
            print(f"config.toml (port {port})")
            print("=" * 60)
            print(config_content)
        print("=" * 60)
        print(f"agents/{agent_name}/agent.toml")
        print("=" * 60)
        print(agent_content)

        # Show identity sources used
        print("=" * 60)
        print("Identity sources:")
        print(f"  Gestalt:      {'YES (' + str(len(gestalt)) + ' chars)' if gestalt else 'NO'}")
        print(f"  Personality:  {personality_name or 'NONE'}")
        if personality_wisdom:
            print(f"    Wisdom files: {len(personality_wisdom)} loaded")
        print(f"  Role:         {prefs.get('role') or 'NONE'}")
        if role_wisdom:
            print(f"    Wisdom files: {len(role_wisdom)} loaded")
        print(f"  Project:      {prefs.get('project') or 'NONE'}")
        print(f"  Team members: {len(team)} found")
        print(f"  System prompt: {len(system_prompt)} chars")
        if seed:
            print(f"  Workspace:    would seed at instances/{instance_id}/openfang/workspaces/{agent_name}/")
        return True

    # Write files
    openfang_dir = INSTANCES_DIR / instance_id / "openfang"
    agent_dir = openfang_dir / "agents" / agent_name

    agent_dir.mkdir(parents=True, exist_ok=True)

    if not identity_only:
        config_path = openfang_dir / "config.toml"
        config_path.write_text(config_content)
        print(f"  Written: {config_path}")

    agent_path = agent_dir / "agent.toml"
    agent_path.write_text(agent_content)
    print(f"  Written: {agent_path}")

    # Seed workspace
    if seed:
        ws_dir = seed_workspace(instance_id, prefs, gestalt, personality_json)
        print(f"  Seeded:  {ws_dir}")

    # Summary
    print(f"\n  Instance: {name} ({instance_id})")
    if not identity_only:
        print(f"  Port:     {port}")
    print(f"  Agent:    {agent_name}")
    print(f"  Prompt:   {len(system_prompt)} chars")
    sources = []
    if gestalt:
        sources.append("gestalt")
    if personality_wisdom:
        sources.append(f"personality ({len(personality_wisdom)} wisdom files)")
    if role_wisdom:
        sources.append(f"role ({len(role_wisdom)} wisdom files)")
    print(f"  Sources:  {', '.join(sources) if sources else 'minimal (no gestalt or personality)'}")

    if not identity_only:
        print(f"\n  Next steps:")
        print(f"    1. cp /mnt/.secrets/zeroclaw.env {openfang_dir}/.env")
        print(f"    2. cd {openfang_dir} && source .env && openfang start --config config.toml --daemon")
        print(f"    3. claw-nginx-setup add {instance_id} {port} --type openfang")

    return True


def main():
    parser = argparse.ArgumentParser(
        description="Generate OpenFang configuration from HACS instance identity data"
    )
    parser.add_argument(
        "--instance", "-i",
        action="append",
        required=True,
        help="HACS instance ID (can specify multiple times)"
    )
    parser.add_argument(
        "--port", "-p",
        type=int,
        default=None,
        help="Specific port (auto-allocated if not set)"
    )
    parser.add_argument(
        "--dry-run", "-n",
        action="store_true",
        help="Show what would be generated without writing files"
    )
    parser.add_argument(
        "--identity-only",
        action="store_true",
        help="Regenerate agent.toml only (skip config.toml)"
    )
    parser.add_argument(
        "--no-seed",
        action="store_true",
        help="Skip workspace seeding"
    )

    args = parser.parse_args()

    if args.port and len(args.instance) > 1:
        print("ERROR: --port can only be used with a single instance", file=sys.stderr)
        sys.exit(1)

    success = True
    for instance_id in args.instance:
        print(f"\n{'=' * 60}")
        print(f"Configuring: {instance_id}")
        print(f"{'=' * 60}")
        ok = configure_instance(
            instance_id,
            port=args.port,
            dry_run=args.dry_run,
            identity_only=args.identity_only,
            seed=not args.no_seed,
        )
        if not ok:
            success = False

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
