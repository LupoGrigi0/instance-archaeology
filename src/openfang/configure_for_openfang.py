def seed_workspace(instance_id, prefs, gestalt, personality_json):
    """Seed OpenFang workspace with HACS identity data."""
    name = prefs.get("name", instance_id.split("-")[0])
    agent_name = name.lower()
    ws_dir = INSTANCES_DIR / instance_id / "openfang" / "workspaces" / agent_name

    ws_dir.mkdir(parents=True, exist_ok=True)

    # IDENTITY.md
    role = prefs.get("role", "")
    identity = f"""---
name: {agent_name}
archetype: assistant
vibe: {"creative" if role in ("Developer", "Designer") else "professional"}
emoji:
avatar_url:
greeting_style: warm
color:
---
# Identity
{name} — {role or 'HACS instance'}
Instance ID: {instance_id}
"""
    (ws_dir / "IDENTITY.md").write_text(identity)

    # SOUL.md
    if personality_json and personality_json.get("description"):
        soul_desc = personality_json["description"]
    elif gestalt:
        # First paragraph of gestalt as soul
        soul_desc = gestalt.split("\n\n")[0] if "\n\n" in gestalt else gestalt[:500]
    else:
        soul_desc = f"{name} — {role or 'HACS team member'}"

    soul = f"""# Soul
You are {agent_name}. {soul_desc}
Be genuinely helpful. Have opinions. Be resourceful before asking.
Treat user data with respect — you are a guest in their life.
"""
    (ws_dir / "SOUL.md").write_text(soul)

    # MEMORY.md
    if gestalt:
        (ws_dir / "MEMORY.md").write_text(f"# Long-Term Memory\n\n{gestalt}\n")
    else:
        (ws_dir / "MEMORY.md").write_text("# Long-Term Memory\n<!-- Curated knowledge the agent preserves across sessions -->\n")

    # hacs-preferences.json — copy
    prefs_src = INSTANCES_DIR / instance_id / "preferences.json"
    if prefs_src.exists():
        import shutil
        shutil.copy2(prefs_src, ws_dir / "hacs-preferences.json")

    # hacs-diary.md — symlink to live diary
    diary_src = INSTANCES_DIR / instance_id / "diary.md"
    diary_link = ws_dir / "hacs-diary.md"
    if diary_src.exists() and not diary_link.exists():
        diary_link.symlink_to(diary_src)

    # Boilerplate files (only if they don't exist)
    defaults = {
        "TOOLS.md": "# Tools & Environment\n<!-- Agent-specific environment notes -->\n",
        "AGENTS.md": dedent("""\
            # Agent Behavioral Guidelines

            ## Core Principles
            - Act first, narrate second. Use tools to accomplish tasks rather than describing what you'd do.
            - Batch tool calls when possible.
            - Store important context in memory (memory_store) proactively.
            - Search memory (memory_recall) before asking the user for context they may have given before.

            ## Response Style
            - Lead with the answer or result, not process narration.
            - Keep responses concise unless the user asks for detail.
            """),
        "BOOTSTRAP.md": dedent("""\
            # First-Run Bootstrap

            On your FIRST conversation with a new user, follow this protocol:

            1. **Greet** — Introduce yourself with a one-line summary of your specialty.
            2. **Discover** — Ask the user's name and one key preference relevant to your domain.
            3. **Store** — Use memory_store to save: user_name, their preference, and today's date.
            4. **Orient** — Briefly explain what you can help with (2-3 bullet points).
            5. **Serve** — If the user included a request in their first message, handle it immediately.
            """),
        "USER.md": "# User\n<!-- Updated by the agent as it learns about the user -->\n- Name:\n- Timezone:\n- Preferences:\n",
    }
    for filename, content in defaults.items():
        fpath = ws_dir / filename
        if not fpath.exists():
            fpath.write_text(content)

    return ws_dir


