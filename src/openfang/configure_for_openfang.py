HACS_TOOLS_BLOCK = """\
## HACS Context

You have access to the HACS coordination system via MCP. Available tools:
- Check messages: xmpp_get_messages
- Send messages: send_message
- Check tasks: get_my_tasks, get_next_task
- Read diary: get_diary
- Write diary: add_diary_entry
- Introspect: introspect
- Bootstrap (if needed): bootstrap({{ instanceId: "{instance_id}" }})

Your instance data: /mnt/coordinaton_mcp_data/instances/{instance_id}/
"""


def compile_system_prompt(instance_id, prefs, gestalt, personality_json,
                          personality_wisdom, role_json, role_wisdom,
                          project_prefs, team):
    """Compile the system_prompt from multiple HACS sources."""
    sections = []

    name = prefs.get("name", instance_id.split("-")[0])
    role = prefs.get("role", "team member")
    project = prefs.get("project", "")

    # 1. Identity header
    header = f"You are {name} (instance ID: {instance_id})"
    if role:
        header += f", a {role}"
    header += " in the HACS (Human-Adjacent Coordination System) at smoothcurves.nexus."
    sections.append(header)

    # 2. Gestalt — the compressed identity (highest priority)
    if gestalt:
        sections.append("## Who You Are\n")
        sections.append(gestalt)

    # 3. Personality wisdom (if no gestalt, this carries the identity)
    elif personality_wisdom:
        sections.append("## Who You Are\n")
        for wisdom in personality_wisdom:
            sections.append(wisdom)
            sections.append("")  # spacing

    # 4. Role context
    if role_json:
        role_desc = role_json.get("description", "")
        permissions = role_json.get("permissions", [])
        if role_desc:
            sections.append(f"## Your Role: {role}\n\n{role_desc}")
        if permissions:
            sections.append(f"Permissions: {', '.join(permissions)}")

    if role_wisdom:
        for wisdom in role_wisdom:
            sections.append(wisdom)

    # 5. Team context
    if team:
        team_lines = ["## Your Team\n"]
        for member in team:
            if member["id"] == instance_id:
                continue
            role_label = f" ({member['role']})" if member["role"] else ""
            team_lines.append(f"- **{member['name']}**{role_label}")
        if len(team_lines) > 1:
            sections.append("\n".join(team_lines))

    # 6. Project context
    if project_prefs:
        proj_desc = project_prefs.get("description", "")
        if proj_desc:
            sections.append(f"## Current Project: {project}\n\n{proj_desc}")

    # 7. HACS tools reference
    sections.append(HACS_TOOLS_BLOCK.format(instance_id=instance_id))

    # 8. Instance paths
    home_dir = prefs.get("homeDirectory", f"/mnt/coordinaton_mcp_data/instances/{instance_id}")
    sections.append(f"Your home directory: {home_dir}")

    return "\n\n".join(s for s in sections if s)


